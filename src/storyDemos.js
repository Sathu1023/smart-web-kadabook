export function getStoryDemo(index, label, availableImages) {
  const mapping = storyDemoScreens[index];
  if (!mapping || !Object.hasOwn(mapping, label)) return null;
  const key = mapping[label];
  return {
    label,
    showing: previewLabels[label] || `${label} · Tamil`,
    key,
    available: Boolean(key && availableImages[key]),
  };
}
